#!/usr/bin/env bash
# Inlines src modules into dist/AnimationPlayer.lua by pure concatenation.
# Each module (return function(A) ... end) is wrapped as (function() <src> end)()
# and bound to a file-scope local; init.lua references those locals.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=dist/AnimationPlayer.lua
mkdir -p dist

emit() { # $1 = local name, $2 = src path
    printf 'local %s = (function()\n' "$1"
    cat "$2"
    printf '\nend)()\n'
}

{
    printf -- '-- AnimationPlayer bundle (generated by build/bundle.sh)\n'
    emit __GUI     src/ui/gui.lua
    emit __STORE   src/core/store.lua
    emit __PLAYER  src/core/player.lua
    emit __PACKS   src/core/packs.lua
    emit __APP     src/app.lua
    cat src/init.lua
} > "$OUT"

echo "built $OUT ($(wc -l < "$OUT") lines)"
